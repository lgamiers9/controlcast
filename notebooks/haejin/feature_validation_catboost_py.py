def run_cat(tag, feats, seed=42, iters=1000, verbose=False):
    """학습 → 2024 예측 → REL/RES 분해"""
    model = CatBoostClassifier(
        iterations=iters,
        learning_rate=0.05,
        depth=6,
        l2_leaf_reg=6.0,
        loss_function="Logloss",
        eval_metric="Logloss",
        random_seed=seed,
        task_type="GPU" if USE_GPU else "CPU",
        verbose=200 if verbose else 0,
        allow_writing_files=False,
    )
    tr_idx = np.flatnonzero(tr_mask)
    va_idx = np.flatnonzero(va_mask)
    model.fit(make_pool(tr_idx, feats))
    p = model.predict_proba(make_pool(va_idx, feats))[:, 1]
    d = decompose(y[va_idx], p)
    print(f"[{tag}] 피처 {len(feats)}개  "
          f"BSS {d['BSS']:8.2f}  REL {d['REL']:.6f}  RES {d['RES']:.6f}  "
          f"mean_pred-r {d['mean_pred-r']:+.4f}")
    return model, p, d

