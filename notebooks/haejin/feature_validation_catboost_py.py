def perm_importance(model, X, y, feats, cats, n_repeats=5, seed=42):
    """예측만 반복하는 permutation importance.
    학습 변동이 개입하지 않아 노이즈 0.000043 문제에서 자유롭다."""
    rng = np.random.default_rng(seed)

    def score(Xd):
        p = model.predict_proba(Xd)[:, 1]
        return -((p - y) ** 2).mean()      # neg Brier

    base = score(X)
    print(f"기준 neg-Brier {base:.6f}")

    rows = []
    for i, f in enumerate(feats, 1):
        drops = []
        col = X[f].to_numpy(copy=True)
        for _ in range(n_repeats):
            Xp = X.copy()
            Xp[f] = rng.permutation(col)
            drops.append(base - score(Xp))
        rows.append({"피처": f, "중요도": np.mean(drops), "표준편차": np.std(drops)})
        if i % 10 == 0:
            print(f"  {i}/{len(feats)}")

    return (pd.DataFrame(rows).sort_values("중요도", ascending=False)
            .reset_index(drop=True))


