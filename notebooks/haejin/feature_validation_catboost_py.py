def decompose(y_true, p, n_bins=20):
    """Brier = REL - RES + UNC

    REL 낮을수록 좋음 (예측 확률이 실제 빈도와 일치)
    RES 높을수록 좋음 (투구별 분별력)

    피처 비교는 RES 로 한다. BSS 는 확률 보정 여부에 따라
    100점 단위로 흔들려 단독 비교 지표로 부적합하다.
    """
    y_true = np.asarray(y_true, float)
    p = np.asarray(p, float)
    r, n = y_true.mean(), len(y_true)
    edges = np.quantile(p, np.linspace(0, 1, n_bins + 1))
    edges[0] -= 1e-9; edges[-1] += 1e-9
    idx = np.digitize(p, edges[1:-1])
    rel = res = 0.0
    for k in np.unique(idx):
        m = idx == k
        w = m.sum() / n
        rel += w * (p[m].mean() - y_true[m].mean()) ** 2
        res += w * (y_true[m].mean() - r) ** 2
    return {"BSS": 100000 * (res - rel) / (r * (1 - r)),
            "REL": rel, "RES": res, "mean_pred-r": p.mean() - r}

